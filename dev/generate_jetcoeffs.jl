# This script generates src/propagation/jetcoeffs.jl, i.e. the methods of
# `TaylorIntegration._allocate_jetcoeffs!` and `TaylorIntegration.jetcoeffs!` of every
# dynamical model decorated with @cyclicbarrier in src/propagation/dynamicalmodels.jl
#
# This script can be run from NEOs.jl root directory with:
#      julia --project dev/generate_jetcoeffs.jl

using TaylorIntegration

const propagation_dir = joinpath(dirname(@__DIR__), "src", "propagation")
const models_file = joinpath(propagation_dir, "dynamicalmodels.jl")
const jetcoeffs_file = joinpath(propagation_dir, "jetcoeffs.jl")

const header = """
# DO NOT MODIFY THIS FILE BY HAND

# Methods of `TaylorIntegration._allocate_jetcoeffs!` and `TaylorIntegration.jetcoeffs!`
# generated by @taylorize for the functions in src/propagation/dynamicalmodels.jl

# To update the functions below do the following:
# 1.- Update the corresponding function in src/propagation/dynamicalmodels.jl
# 2.- Run, from NEOs.jl root directory:
#     julia --project dev/generate_jetcoeffs.jl
# The script runs `TaylorIntegration._make_parsed_jetcoeffs` on every function decorated
# with @cyclicbarrier in src/propagation/dynamicalmodels.jl, and decorates the resulting
# methods with @cyclicbarrier as well. This macro generates the serial and multi-threaded
# versions of each function (see its docstring); in particular, it unfolds the evaluation
# of the Solar System ephemerides (`local sseph_ephU = params.sseph(dsj2k)` and
# analogously for params.acceph and params.poteph) and runs the Threads.@threads loops
# via a cyclic barrier, so tasks are spawned only once per call.
# 3.- Check that the integrations with `parse_eqs = true` and `parse_eqs = false`
#     agree, both with `threads = true` and `threads = false`
"""

# Function definitions decorated with @cyclicbarrier in `ex`, in order of appearance
function cyclicbarrier_functions!(fdefs::Vector{Expr}, ex)
    ex isa Expr || return fdefs
    if ex.head === :macrocall && ex.args[1] === Symbol("@cyclicbarrier")
        push!(fdefs, ex.args[end])
    else
        foreach(arg -> cyclicbarrier_functions!(fdefs, arg), ex.args)
    end
    return fdefs
end

# Name of the function defined by `fdef`
function function_name(fdef::Expr)
    call = fdef.args[1]
    while call.head === :where
        call = call.args[1]
    end
    return call.args[1]::Symbol
end

# Remove the LineNumberNodes of `ex`, including those of macro calls
function striplines!(ex)
    if ex isa Expr
        ex.head === :macrocall && (ex.args[2] = nothing)
        filter!(arg -> !(arg isa LineNumberNode), ex.args)
        foreach(striplines!, ex.args)
    end
    return ex
end

# Rename the auxiliary variables `tmpN` as `tmp1`, `tmp2`, ... in order of appearance,
# so the output of each model does not depend on the models parsed before it
function renametmps!(names::Dict{Symbol, Symbol}, ex)
    if ex isa Symbol && occursin(r"^tmp\d+$", String(ex))
        return get!(() -> Symbol("tmp", length(names) + 1), names, ex)
    elseif ex isa Expr
        for i in eachindex(ex.args)
            ex.args[i] = renametmps!(names, ex.args[i])
        end
    end
    return ex
end

models = Meta.parseall(read(models_file, String); filename = models_file)
fdefs = cyclicbarrier_functions!(Expr[], models)

open(jetcoeffs_file, "w") do io
    print(io, header)
    for fdef in fdefs
        jetcoeffs, allocate, _ = TaylorIntegration._make_parsed_jetcoeffs(deepcopy(fdef))
        names = Dict{Symbol, Symbol}()
        allocate = renametmps!(names, striplines!(allocate))
        jetcoeffs = renametmps!(names, striplines!(jetcoeffs))
        print(io, "\n# ", function_name(fdef), "\n")
        print(io, "@cyclicbarrier ", allocate, "\n\n")
        print(io, "@cyclicbarrier ", jetcoeffs, "\n")
    end
end

println("Generated the parsed methods of ", join(function_name.(fdefs), ", "),
    " in ", jetcoeffs_file)
